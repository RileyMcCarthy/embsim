/// The canonical name reaches the built board: two sheets both labelled
/// `SIGNAL` stay two nets with two distinguishable names.
#[rstest]
fn board_build_keeps_same_leaf_nets_distinct() {
    const TWO_SHEETS: &str = r#"(export (version "E")
        (components
          (comp (ref "R1") (value "10k")
            (libsource (lib "Device") (part "R_Small"))
            (sheetpath (names "/Sheet2/") (tstamps "/1111/")))
          (comp (ref "R2") (value "10k")
            (libsource (lib "Device") (part "R_Small"))
            (sheetpath (names "/Sheet3/") (tstamps "/2222/"))))
        (nets
          (net (code "1") (name "/Sheet2/SIGNAL")
            (node (ref "R1") (pin "1") (pintype "passive")))
          (net (code "2") (name "/Sheet3/SIGNAL")
            (node (ref "R2") (pin "1") (pintype "passive")))
          (net (code "3") (name "/Sheet2/~{OE}")
            (node (ref "R1") (pin "2") (pintype "passive"))
            (node (ref "R2") (pin "2") (pintype "passive")))))"#;

    let board = Board::from_netlist(parse(TWO_SHEETS).unwrap(), &PartRegistry::new())
        .expect("two resistors on three nets build");

    let names: Vec<&str> = board.nets().iter().map(|n| n.name.as_str()).collect();
    assert_eq!(names, ["/Sheet2/SIGNAL", "/Sheet3/SIGNAL", "/Sheet2/~OE"]);
    assert_eq!(board.nets()[0].nodes.len(), 1);
    assert_eq!(board.nets()[2].nodes.len(), 2);
}
