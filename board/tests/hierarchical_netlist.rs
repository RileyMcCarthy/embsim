/// Every component carries the sheet instance it was placed on.
#[rstest]
#[case::root("/", 21)]
#[case::sheet2("/MaD_Edge_Sheet2/", 101)]
#[case::sheet3("/MaD_Edge_Sheet3/", 46)]
fn component_sheetpaths_distribute_across_three_sheets(
    #[case] sheetpath: &str,
    #[case] expected: usize,
) {
    let parsed = edge();
    assert_eq!(
        parsed
            .components
            .iter()
            .filter(|c| c.sheetpath == sheetpath)
            .count(),
        expected
    );
}

/// Overline pinfunctions from the real export normalize to one spelling.
#[rstest]
#[case::gate("U24", "12", "~G")]
#[case::enable("U1", "4", "~ON")]
fn overline_pinfunctions_normalize(
    #[case] reference: &str,
    #[case] pin: &str,
    #[case] expected: &str,
) {
    let parsed = edge();
    let node = parsed
        .nets
        .iter()
        .flat_map(|n| n.nodes.iter())
        .find(|n| n.reference == reference && n.pin == pin)
        .unwrap_or_else(|| panic!("{reference}.{pin} present"));
    let function = node.pinfunction.as_deref().expect("pinfunction present");
    assert_eq!(normalize_pin_name(function), expected);
}

/// A project-local / cached symbol exports with an empty libsource lib —
/// classification keys on `part`, so this must not be an error.
#[rstest]
fn empty_libsource_lib_names_survive_parsing() {
    let parsed = edge();
    let ic6 = parsed
        .components
        .iter()
        .find(|c| c.reference == "IC6")
        .expect("IC6 present");
    assert_eq!(ic6.lib, "");
    assert_eq!(ic6.part, "NSI50010YT1G_1");
    assert!(parsed.components.iter().all(|c| !c.part.is_empty()));
}

/// No component in this export sets the KiCad `dnp` property or the
/// `value == "X"` convention — the whole board is fitted, so a future DNP
/// regression here is visible.
#[rstest]
fn the_edgeboard_export_has_no_dnp_components() {
    let parsed = edge();
    assert!(parsed.components.iter().all(|c| !c.dnp && c.value != "X"));
}

