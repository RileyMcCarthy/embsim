/// Sheet-scoped names keep their full path, and the two sub-sheets are the
/// only scopes in play.
#[rstest]
fn sheet_scoped_net_names_keep_their_full_path() {
    let parsed = edge();

    let scoped: Vec<&str> = parsed
        .nets
        .iter()
        .map(|n| n.name.as_str())
        .filter(|n| net_sheet_path(n).is_some())
        .collect();
    assert_eq!(scoped.len(), EXPECTED_SHEET_SCOPED_NETS);

    let paths: HashSet<&str> = scoped.iter().filter_map(|n| net_sheet_path(n)).collect();
    assert_eq!(
        paths,
        HashSet::from(["/MaD_Edge_Sheet2/", "/MaD_Edge_Sheet3/"])
    );

    // Landmarks: the isolated force-gauge UART on sheet 2 and the servo pulse
    // pair on sheet 3.
    let ifg_rx = parsed
        .nets
        .iter()
        .find(|n| n.name == "/MaD_Edge_Sheet2/IFG_RX")
        .expect("sheet-2 IFG_RX present");
    assert_eq!(net_short_label(&ifg_rx.name), "IFG_RX");
    assert_eq!(ifg_rx.nodes.len(), 2);
    assert!(parsed
        .nets
        .iter()
        .any(|n| n.name == "/MaD_Edge_Sheet3/SC_PUL+"));

    // Global labels and power nets stay unscoped.
    for global in ["GND", "+3.3V", "+5V", "RESn", "P16"] {
        let net = parsed
            .nets
            .iter()
            .find(|n| n.name == global)
            .unwrap_or_else(|| panic!("{global} present"));
        assert_eq!(net_sheet_path(&net.name), None);
    }
}

/// Names are unique *as canonical strings*; leaf labels are not required to
/// be. (In this board no two sheets happen to reuse a leaf, so the
/// same-leaf-collision case is covered by the synthetic netlist in
/// `netlist.rs`'s unit tests and by `board_build_keeps_same_leaf_nets_distinct`
/// below.)
#[rstest]
fn canonical_net_names_are_unique() {
    let parsed = edge();
    let names: HashSet<&str> = parsed.nets.iter().map(|n| n.name.as_str()).collect();
    assert_eq!(names.len(), EXPECTED_NETS);
}

/// KiCad's synthesized names: 65 `Net-(…)` unlabeled nets and 47
/// `unconnected-(…)` stubs, every stub a single pin the schematic marks
/// no-connect.
#[rstest]
fn autogenerated_names_describe_single_pin_no_connect_stubs() {
    let parsed = edge();

    let unconnected: Vec<_> = parsed
        .nets
        .iter()
        .filter(|n| n.name.starts_with("unconnected-("))
        .collect();
    assert_eq!(unconnected.len(), 47);
    for net in &unconnected {
        assert!(is_autogenerated_net_name(&net.name));
        assert_eq!(net.nodes.len(), 1, "{} should be a stub", net.name);
        let pintype = net.nodes[0]
            .pintype
            .as_deref()
            .unwrap_or_else(|| panic!("{} node carries a pintype", net.name));
        assert!(
            pintype.contains("no_connect"),
            "{} node pintype {pintype:?} should be a no-connect",
            net.name
        );
    }

    assert_eq!(
        parsed
            .nets
            .iter()
            .filter(|n| n.name.starts_with("Net-("))
            .count(),
        65
    );
}

