//! Hierarchical (multi-sheet) netlist ingestion, against the real EdgeBoard
//! export.
//!
//! # Fixture provenance
//!
//! `fixtures/mad_edge.net` is a `kicad-cli sch export netlist` of the MaD
//! repo's `Hardware/EdgeBoard/KiCad/MaD_Edge.kicad_sch` (three hierarchical
//! sheets: the root plus `MaD_Edge_Sheet2` and `MaD_Edge_Sheet3`), taken
//! 2026-07-26 with Eeschema 9.0.6 — export version `"E"`, 168 components,
//! 243 nets, 718 nodes. The file carries the same provenance as a `;` comment
//! header, which the parser skips wherever whitespace is legal.
//!
//! The export is **not byte-stable**: `(design (source …))` is an absolute
//! path and `(date …)` is the export timestamp, so a regeneration check
//! compares the parsed *shape* asserted here — counts, membership, sheet
//! paths — never bytes. `tests/fixture_smoke.rs` holds the cheap text-level
//! landmarks; this binary holds the parse-level truth.
//!
//! Why a second fixture at all: `ds2_addon.net` is flat, so it cannot
//! exercise sheet-scoped net names, per-component sheet paths, an 80-pin edge
//! connector, or an empty libsource lib name. All four appear here.

use std::collections::{HashMap, HashSet};

use rstest::rstest;

use embsim_board::netlist::{
    is_autogenerated_net_name, net_sheet_path, net_short_label, normalize_pin_name, parse,
};
use embsim_board::{Board, ParsedNetlist, PartRegistry};

const MAD_EDGE: &str = include_str!("fixtures/mad_edge.net");

/// Component count of the committed export.
const EXPECTED_COMPONENTS: usize = 168;
/// Net count of the committed export.
const EXPECTED_NETS: usize = 243;
/// Total `(node …)` membership entries of the committed export.
const EXPECTED_NODES: usize = 718;
/// Nets whose name is sheet-scoped (a local label on a sub-sheet).
const EXPECTED_SHEET_SCOPED_NETS: usize = 53;

fn edge() -> ParsedNetlist {
    parse(MAD_EDGE).expect("the EdgeBoard fixture parses")
}

// ============================================================
// Shape
// ============================================================

#[rstest]
fn mad_edge_parses_with_the_exported_shape() {
    let parsed = edge();
    assert_eq!(parsed.version, "E");
    assert_eq!(parsed.components.len(), EXPECTED_COMPONENTS);
    assert_eq!(parsed.nets.len(), EXPECTED_NETS);
    assert_eq!(
        parsed.nets.iter().map(|n| n.nodes.len()).sum::<usize>(),
        EXPECTED_NODES
    );
}

/// The provenance header is a `;` comment block, and its presence must not
/// change what the parser sees.
#[rstest]
fn fixture_carries_a_provenance_header_the_parser_skips() {
    assert!(
        MAD_EDGE.starts_with("; embsim-board netlist fixture"),
        "the committed fixture must keep its provenance header"
    );
    assert!(MAD_EDGE.contains("kicad-cli sch export netlist"));
    let stripped: String = MAD_EDGE
        .lines()
        .skip_while(|l| l.starts_with(';'))
        .collect::<Vec<_>>()
        .join("\n");
    assert_eq!(parse(&stripped).unwrap(), edge());
}

// ============================================================
// Membership is lossless
// ============================================================

/// Every net node names a declared component, every declared component owns
/// at least one node, and no pin appears on two nets — i.e. the parsed graph
/// can be walked back to the same membership the export describes.
#[rstest]
fn membership_round_trips_against_the_component_list() {
    let parsed = edge();

    let declared: HashSet<&str> = parsed
        .components
        .iter()
        .map(|c| c.reference.as_str())
        .collect();
    assert_eq!(declared.len(), EXPECTED_COMPONENTS, "references are unique");

    let mut pins_by_ref: HashMap<&str, HashSet<&str>> = HashMap::new();
    let mut owner_of_pin: HashMap<(&str, &str), &str> = HashMap::new();
    for net in &parsed.nets {
        for node in &net.nodes {
            assert!(
                declared.contains(node.reference.as_str()),
                "net {:?} references undeclared component {:?}",
                net.name,
                node.reference
            );
            assert!(
                pins_by_ref
                    .entry(node.reference.as_str())
                    .or_default()
                    .insert(node.pin.as_str()),
                "{}.{} appears twice",
                node.reference,
                node.pin
            );
            let previous =
                owner_of_pin.insert((node.reference.as_str(), node.pin.as_str()), &net.name);
            assert_eq!(
                previous, None,
                "{}.{} is a member of two nets",
                node.reference, node.pin
            );
        }
    }

    assert_eq!(owner_of_pin.len(), EXPECTED_NODES);
    let unwired: Vec<&str> = declared
        .iter()
        .copied()
        .filter(|r| !pins_by_ref.contains_key(r))
        .collect();
    assert!(
        unwired.is_empty(),
        "components with no net membership: {unwired:?}"
    );
}

/// J3 is the P2 Edge module socket — all 80 edge fingers must land in the
/// graph (the module's own netlist calls the mating connector J203).
#[rstest]
fn edge_module_socket_keeps_all_eighty_fingers() {
    let parsed = edge();
    let socket = parsed
        .components
        .iter()
        .find(|c| c.reference == "J3")
        .expect("J3 present");
    assert_eq!(socket.part, "P2_EDGE_MODULE_SOCKET");

    let pins: HashSet<&str> = parsed
        .nets
        .iter()
        .flat_map(|n| n.nodes.iter())
        .filter(|n| n.reference == "J3")
        .map(|n| n.pin.as_str())
        .collect();
    assert_eq!(pins.len(), 80);
}

